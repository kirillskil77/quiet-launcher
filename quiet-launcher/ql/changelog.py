DEFAULT_NEWS = ["Мелкие исправления и улучшения."]


def parse(v):
    out = []
    for p in str(v).strip().lstrip("vV").split("."):
        digits = "".join(ch for ch in p if ch.isdigit())
        out.append(int(digits) if digits else 0)
    while len(out) < 3:
        out.append(0)
    return tuple(out[:3])


def generation(v):
    a = parse(v)
    return "%d.%d" % (a[0], a[1])


def news_for(version):
    """Список для приветствия новичка: всё поколение этой версии."""
    return list(GENERATIONS.get(generation(version)) or DEFAULT_NEWS)


def updated_items(old, new):
    """Что показать при обновлении со старой версии на новую.
    Возвращает (пункты, прошлые): если поколение то же — только мелкие правки между версиями;
    если новое — весь список нового поколения, а список прежнего поколения отдельно (по ссылке)."""
    og, ng = generation(old), generation(new)
    if og == ng:
        items = []
        for v in sorted(PATCHES, key=parse):
            if parse(old) < parse(v) <= parse(new):
                items += PATCHES[v]
        return (items or DEFAULT_NEWS), None
    return list(GENERATIONS.get(ng) or DEFAULT_NEWS), list(GENERATIONS.get(og) or []) or None


def counter_path(old, new, limit=40):
    """Версии, через которые «пробегает» счётчик: 1.3.2 → 1.3.3 … 1.3.9 → 1.4.0."""
    a, b = parse(old), parse(new)
    if a >= b:
        return [".".join(map(str, b))]
    cur, path = list(a), []
    while tuple(cur) < b and len(path) < 500:
        if cur[2] < 9 and (cur[0], cur[1]) != (b[0], b[1]):
            cur[2] += 1
        elif (cur[0], cur[1]) == (b[0], b[1]):
            cur[2] += 1
        else:
            cur[1] += 1
            cur[2] = 0
        path.append(".".join(map(str, cur)))
    if len(path) > limit:                          # длинный путь — прореживаем, но начало и конец сохраняем
        step = len(path) / float(limit - 1)
        path = [path[int(i * step)] for i in range(limit - 1)] + [path[-1]]
    return [".".join(map(str, a))] + path
